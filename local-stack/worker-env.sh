#!/bin/sh
# Writes .worker.env at the repo root: only the .env lines the Docker worker reads, so its
# container never holds the gateway's or the control plane's secrets (ADR 0006). The worker's
# one secret is its model provider key (MODEL_<NAME>_API_KEY, ADR 0010).
# Rewritten on every make target from .env (edit .env, never this file). Git- and docker-ignored.
# Endpoints, the queue URL, the control plane and gateway URLs and TOOLS_PROVIDER come from
# docker-compose.yml, not from here.
set -eu

cd "$(dirname "$0")/.."
ALLOWED='MODEL_[A-Z0-9_]+|AWS_REGION|AWS_ACCESS_KEY_ID|AWS_SECRET_ACCESS_KEY|STATE_BACKEND|STATE_TABLE|QUEUE_BACKEND|WORKER_CONCURRENCY|LOG_LEVEL|RUN_VISIBILITY_SECONDS'

umask 077
tmp=.worker.env.tmp
{
  echo "# Generated by local-stack/worker-env.sh from .env; do not edit."
  grep -E "^($ALLOWED)=" .env || true
} > "$tmp"
mv "$tmp" .worker.env

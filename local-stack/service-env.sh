#!/bin/sh
# Writes one env file per service at the repo root (.worker.env, .control-plane.env) holding only
# the .env lines that service reads, so no container holds another service's secrets (ADR 0006).
# Rewritten on every make target from .env (edit .env, never these files). Git- and docker-ignored,
# mode 600. Settings compose sets per service (endpoints, RUN_QUEUE_URL, CONTROL_PLANE_URL,
# TOOLS_PROVIDER, ...) and the run-token keys (.run-token-*.env) do not come from here. The tool
# gateway gets named settings in docker-compose.yml instead.
#
# A new setting a service reads goes in that service's list below.
set -eu

cd "$(dirname "$0")/.."

# Worker: its one secret is the model provider key (MODEL_<NAME>_API_KEY, ADR 0010).
WORKER='MODEL_[A-Z0-9_]+|AWS_REGION|AWS_ACCESS_KEY_ID|AWS_SECRET_ACCESS_KEY|STATE_BACKEND|STATE_TABLE|QUEUE_BACKEND|WORKER_CONCURRENCY|LOG_LEVEL|RUN_VISIBILITY_SECONDS'

# Control plane: the ${...} names in control-plane/src/main/resources/application.yml, plus the
# AWS SDK's region and (dummy) keys. Its secrets: tenant API key, webhook secret, Slack.
CONTROL_PLANE='STORE_BACKEND|CONTROL_PLANE_TABLE|QUEUE_BACKEND|TENANT_ID|TENANT_API_KEY|GITHUB_WEBHOOK_SECRET|SLACK_[A-Z0-9_]+|SWEEP_INTERVAL_SECONDS|SWEEP_QUEUED_AFTER_SECONDS|APPROVAL_TIMEOUT_HOURS|AWS_REGION|AWS_ACCESS_KEY_ID|AWS_SECRET_ACCESS_KEY'

umask 077

# write <file> <allowed names pattern>
write() {
  tmp="$1.tmp"
  {
    echo "# Generated by local-stack/service-env.sh from .env; do not edit."
    grep -E "^($2)=" .env || true
  } > "$tmp"
  mv "$tmp" "$1"
}

write .worker.env "$WORKER"
write .control-plane.env "$CONTROL_PLANE"
